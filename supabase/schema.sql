-- Gera número sequencial automático (ex: 000001) quando não informado
CREATE OR REPLACE FUNCTION public.gerar_numero_pedido()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  v_seq BIGINT;
  v_num TEXT;
BEGIN
  IF NEW.numero IS NULL OR btrim(NEW.numero) = '' THEN
    LOOP
      v_seq := nextval('public.pedido_numero_seq');
      v_num := lpad(v_seq::text, 6, '0');
      EXIT WHEN NOT EXISTS (SELECT 1 FROM public.pedidos WHERE numero = v_num);
    END LOOP;
    NEW.numero := v_num;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_pedidos_numero ON public.pedidos;
CREATE TRIGGER trg_pedidos_numero
  BEFORE INSERT ON public.pedidos
  FOR EACH ROW EXECUTE FUNCTION public.gerar_numero_pedido();

-- Cria perfil automaticamente ao cadastrar usuário no Supabase Auth
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_total_perfis BIGINT;
BEGIN
  SELECT COUNT(*) INTO v_total_perfis FROM public.perfis;

  INSERT INTO public.perfis (id, nome, email, perfil, ativo)
  VALUES (
    NEW.id,
    COALESCE(NULLIF(btrim(NEW.raw_user_meta_data->>'nome'), ''), split_part(NEW.email, '@', 1)),
    COALESCE(NEW.email, ''),
    CASE WHEN v_total_perfis = 0 THEN 'admin' ELSE 'atendente' END,
    true
  )
  ON CONFLICT (id) DO NOTHING;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Função auxiliar para verificar usuário autenticado e ativo nas políticas RLS
CREATE OR REPLACE FUNCTION public.usuario_autenticado_ativo()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT auth.uid() IS NOT NULL
    AND COALESCE(
      (SELECT ativo FROM public.perfis WHERE id = auth.uid() LIMIT 1),
      true
    );
$$;

