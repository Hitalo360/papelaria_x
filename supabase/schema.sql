-- ----------------------------------------------------------------------------
-- 1. Tabela de Perfis (vinculada ao Supabase Auth)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.perfis (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  nome TEXT NOT NULL,
  email TEXT NOT NULL,
  perfil TEXT NOT NULL DEFAULT 'admin' CHECK (perfil IN ('admin', 'atendente')),
  ativo BOOLEAN NOT NULL DEFAULT true,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- 2. Tabela de Clientes (Unicidade por telefone_limpo)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.clientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  telefone TEXT NOT NULL,
  telefone_limpo TEXT NOT NULL UNIQUE,
  empresa TEXT,
  observacoes TEXT,
  ativo BOOLEAN NOT NULL DEFAULT true,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_clientes_nome ON public.clientes (nome);
CREATE INDEX IF NOT EXISTS idx_clientes_ativo ON public.clientes (ativo);

-- ----------------------------------------------------------------------------
-- 3. Tabela de Categorias de Produtos e Serviços
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.categorias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL UNIQUE,
  descricao TEXT,
  ativo BOOLEAN NOT NULL DEFAULT true,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- 4. Tabela de Produtos e Serviços
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.produtos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoria_id BIGINT NOT NULL REFERENCES public.categorias(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  nome TEXT NOT NULL,
  codigo TEXT NOT NULL UNIQUE,
  descricao TEXT,
  preco NUMERIC(10,2) NOT NULL DEFAULT 0.00 CHECK (preco >= 0),
  unidade_medida TEXT NOT NULL DEFAULT 'un',
  ativo BOOLEAN NOT NULL DEFAULT true,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_produtos_categoria ON public.produtos (categoria_id);
CREATE INDEX IF NOT EXISTS idx_produtos_nome ON public.produtos (nome);
CREATE INDEX IF NOT EXISTS idx_produtos_ativo ON public.produtos (ativo);

-- ----------------------------------------------------------------------------
-- 5. Tabela de Pedidos + Numeração Automática
-- ----------------------------------------------------------------------------
CREATE SEQUENCE IF NOT EXISTS public.pedido_numero_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS public.pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero TEXT NOT NULL UNIQUE,
  cliente_id BIGINT NOT NULL REFERENCES public.clientes(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  usuario_id UUID REFERENCES auth.users(id) ON UPDATE CASCADE ON DELETE SET NULL,
  data_cadastro TIMESTAMPTZ NOT NULL DEFAULT now(),
  data_previsao DATE,
  subtotal NUMERIC(10,2) NOT NULL DEFAULT 0.00 CHECK (subtotal >= 0),
  desconto NUMERIC(10,2) NOT NULL DEFAULT 0.00 CHECK (desconto >= 0),
  valor_total NUMERIC(10,2) NOT NULL DEFAULT 0.00 CHECK (valor_total >= 0),
  status TEXT NOT NULL DEFAULT 'aguardando_confirmacao' CHECK (
    status IN (
      'aguardando_confirmacao',
      'confirmado',
      'em_producao',
      'pronto_retirada',
      'entregue',
      'cancelado'
    )
  ),
  observacoes TEXT,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_pedidos_cliente ON public.pedidos (cliente_id);
CREATE INDEX IF NOT EXISTS idx_pedidos_usuario ON public.pedidos (usuario_id);
CREATE INDEX IF NOT EXISTS idx_pedidos_status ON public.pedidos (status);
CREATE INDEX IF NOT EXISTS idx_pedidos_data_cadastro ON public.pedidos (data_cadastro DESC);

-- ----------------------------------------------------------------------------
-- 6. Tabela de Itens dos Pedidos
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.pedido_itens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES public.pedidos(id) ON UPDATE CASCADE ON DELETE CASCADE,
  produto_id BIGINT REFERENCES public.produtos(id) ON UPDATE CASCADE ON DELETE SET NULL,
  descricao_item TEXT NOT NULL,
  unidade_medida TEXT NOT NULL DEFAULT 'un',
  quantidade NUMERIC(10,2) NOT NULL DEFAULT 1.00 CHECK (quantidade > 0),
  valor_unitario NUMERIC(10,2) NOT NULL DEFAULT 0.00 CHECK (valor_unitario >= 0),
  subtotal NUMERIC(10,2) NOT NULL DEFAULT 0.00 CHECK (subtotal >= 0)
);

CREATE INDEX IF NOT EXISTS idx_pedido_itens_pedido ON public.pedido_itens (pedido_id);
CREATE INDEX IF NOT EXISTS idx_pedido_itens_produto ON public.pedido_itens (produto_id);

-- ----------------------------------------------------------------------------
-- 7. Tabela de Histórico de Status dos Pedidos
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.pedido_historico (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES public.pedidos(id) ON UPDATE CASCADE ON DELETE CASCADE,
  usuario_id UUID REFERENCES auth.users(id) ON UPDATE CASCADE ON DELETE SET NULL,
  usuario_nome TEXT NOT NULL DEFAULT 'Sistema',
  status_anterior TEXT,
  status_novo TEXT NOT NULL,
  observacao TEXT,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_historico_pedido ON public.pedido_historico (pedido_id);
CREATE INDEX IF NOT EXISTS idx_historico_usuario ON public.pedido_historico (usuario_id);

-- ----------------------------------------------------------------------------
-- 8. Tabela de Configurações e Modelos de WhatsApp
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.configuracoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chave TEXT NOT NULL UNIQUE,
  valor TEXT,
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

